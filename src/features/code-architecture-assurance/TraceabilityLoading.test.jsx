import React from 'react';
import {act} from 'react';
import {createRoot} from 'react-dom/client';
import Panel from './TraceabilityMatrixPanel';
import {loadArtifactRowsAsync} from './artifactUtils';
jest.mock('./artifactUtils',()=>({...jest.requireActual('./artifactUtils'),loadArtifactRowsAsync:jest.fn()}));
jest.mock('lucide-react',()=>{const Icon=()=>null;return new Proxy({},{get:()=>Icon});});
global.IS_REACT_ACT_ENVIRONMENT=true;
let host,root;
beforeEach(()=>{jest.useFakeTimers();host=document.createElement('div');document.body.appendChild(host);root=createRoot(host);});
afterEach(()=>{act(()=>root.unmount());host.remove();jest.useRealTimers();jest.clearAllMocks();});
it('uses one stable loading state for storage and chain building before displaying the matrix',async()=>{
 const releases=[];loadArtifactRowsAsync.mockImplementation(()=>new Promise(resolve=>releases.push(resolve)));
 act(()=>root.render(<Panel cbaRows={[]} project={{id:'p'}} repo={{id:'r'}}/>));
 expect(host.querySelectorAll('[role="progressbar"]')).toHaveLength(1);
 expect(host.querySelector('[role="progressbar"]').hasAttribute('aria-valuenow')).toBe(false);
 expect(host.querySelector('table')).toBeNull();
 await act(async()=>releases[0]([]));
 expect(host.querySelectorAll('[role="progressbar"]')).toHaveLength(1);
 expect(host.querySelector('[role="progressbar"]').hasAttribute('aria-valuenow')).toBe(false);
 await act(async()=>releases.slice(1).forEach(resolve=>resolve([])));
 expect(host.querySelector('[role="progressbar"]').getAttribute('aria-label')).toBe('Loading traceability matrix');
 act(()=>jest.runAllTimers());expect(host.querySelector('table')).not.toBeNull();
 expect(host.querySelector('[role="progressbar"]')).toBeNull();
});
it('ends loading on a failed read and offers a retry',async()=>{
 loadArtifactRowsAsync.mockRejectedValue(new Error('Read failed'));
 await act(async()=>root.render(<Panel project={{id:'p'}} repo={{id:'r'}}/>));
 expect(host.querySelector('[role="progressbar"]')).toBeNull();
 expect(host.querySelector('[role="alert"]').textContent).toContain('Read failed');
 loadArtifactRowsAsync.mockResolvedValue([]);
 await act(async()=>[...host.querySelectorAll('button')].find(b=>b.textContent==='Retry loading').click());
 act(()=>jest.runAllTimers());expect(host.querySelector('table')).not.toBeNull();
});
it('does not restart the spinner when other reads finish after failure',async()=>{
 const releases=[];
 loadArtifactRowsAsync.mockRejectedValueOnce(new Error('Read failed')).mockImplementation(()=>new Promise(resolve=>releases.push(resolve)));
 await act(async()=>root.render(<Panel project={{id:'p'}} repo={{id:'r'}}/>));
 await act(async()=>releases.forEach(resolve=>resolve([])));
 expect(host.querySelector('[role="alert"]').textContent).toContain('Read failed');
 expect(host.querySelector('[role="progressbar"]')).toBeNull();
});
it('ignores artifact changes belonging to another project',async()=>{
 loadArtifactRowsAsync.mockResolvedValue([]);
 await act(async()=>root.render(<Panel project={{id:'p'}} repo={{id:'r'}}/>));
 act(()=>jest.runAllTimers());loadArtifactRowsAsync.mockClear();
 await act(async()=>window.dispatchEvent(new CustomEvent('xhandle:code-architecture-assurance:changed',{detail:{projectId:'other',repoId:'r'}})));
 expect(loadArtifactRowsAsync).not.toHaveBeenCalled();
});
it('retains the mounted matrix through background failure and retry',async()=>{
 const cbaRows=[{traceId:'F',from:'A',action:'call',to:'B'}];
 loadArtifactRowsAsync.mockResolvedValue([]);
 await act(async()=>root.render(<Panel project={{id:'p'}} repo={{id:'r'}} cbaRows={cbaRows}/>));
 act(()=>jest.runAllTimers());const table=host.querySelector('table');
 expect(host.textContent).toContain('1 of 1 rows');
 let rejectFirst;
 loadArtifactRowsAsync.mockImplementationOnce(()=>new Promise((resolve,reject)=>{rejectFirst=reject;}));
 await act(async()=>window.dispatchEvent(new CustomEvent('xhandle:code-architecture-assurance:changed',{detail:{projectId:'p',repoId:'r'}})));
 expect(host.querySelector('table')).toBe(table);
 await act(async()=>rejectFirst(new Error('Storage timeout')));
 expect(host.querySelector('[role="alert"]').textContent).toContain('Storage timeout');
 expect(host.querySelector('table')).toBe(table);
 loadArtifactRowsAsync.mockResolvedValue([]);
 await act(async()=>[...host.querySelectorAll('button')].find(b=>b.textContent==='Retry loading').click());
 act(()=>jest.runAllTimers());
 expect(host.querySelector('[role="alert"]')).toBeNull();
 expect(host.querySelector('table')).toBe(table);
});
it('hides the previous scope immediately and ignores obsolete read completions',async()=>{
 const cbaRows=[{traceId:'F',from:'A',action:'call',to:'B'}];
 loadArtifactRowsAsync.mockResolvedValue([]);
 await act(async()=>root.render(<Panel project={{id:'p'}} repo={{id:'r'}} cbaRows={cbaRows}/>));
 act(()=>jest.runAllTimers());expect(host.querySelector('table')).not.toBeNull();
 const oldReleases=[];loadArtifactRowsAsync.mockImplementation(()=>new Promise(resolve=>oldReleases.push(resolve)));
 act(()=>root.render(<Panel project={{id:'q'}} repo={{id:'r'}} cbaRows={cbaRows}/>));
 expect(host.querySelector('table')).toBeNull();
 const newReleases=[];loadArtifactRowsAsync.mockImplementation(()=>new Promise(resolve=>newReleases.push(resolve)));
 act(()=>root.render(<Panel project={{id:'z'}} repo={{id:'r'}} cbaRows={[]}/>));
 await act(async()=>oldReleases.forEach(resolve=>resolve([])));act(()=>jest.runAllTimers());
 expect(host.querySelector('table')).toBeNull();
 await act(async()=>newReleases.forEach(resolve=>resolve([])));act(()=>jest.runAllTimers());
 expect(host.querySelector('table')).not.toBeNull();
 expect(host.textContent).toContain('0 of 0 rows');
});

it('keeps a single indicator when a refresh overlaps preparation of a large matrix',async()=>{
 const cbaRows=Array.from({length:250},(_,index)=>({traceId:`F-${index}`,from:`Source ${index}`,action:'call',to:`Target ${index}`}));
 loadArtifactRowsAsync.mockResolvedValue([]);
 await act(async()=>root.render(<Panel cbaRows={cbaRows} project={{id:'large'}} repo={{id:'r'}}/>));
 act(()=>jest.advanceTimersToNextTimer());
 expect(host.querySelectorAll('[role="progressbar"]')).toHaveLength(1);
 const pending=[];loadArtifactRowsAsync.mockImplementation(()=>new Promise(resolve=>pending.push(resolve)));
 await act(async()=>[...host.querySelectorAll('button')].find(button=>button.textContent==='Refresh Traceability').click());
 expect(host.querySelectorAll('[role="progressbar"]')).toHaveLength(1);
 expect(host.querySelector('[role="progressbar"]').getAttribute('aria-label')).toBe('Loading traceability matrix');
 await act(async()=>pending.forEach(resolve=>resolve([])));
 for(let i=0;i<30 && host.querySelector('[role="progressbar"]');i++)act(()=>jest.runOnlyPendingTimers());
 expect(host.querySelector('[role="progressbar"]')).toBeNull();
 expect(host.querySelector('table')).not.toBeNull();
 expect(host.textContent).toContain('250 of 250 rows');
});
