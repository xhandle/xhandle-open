function resolveModel(args = {}) {
  return loadSysMLV2Model(args.modelId, args.projectId) || ensureDefaultSysMLV2Model(args.projectId);
}

function findElement(model, ref) {
  if (!ref) return null;
  return (model.elements || []).find((element) => element.id === ref || String(element.name).toLowerCase() === String(ref).toLowerCase()) || null;
}

