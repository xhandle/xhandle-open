// Read-only investigation of production behavior in isolated synthetic browser storage.
// AI responses are mocked; no paid model calls or customer projects are accessed.
const assert = require('node:assert/strict');
const {chromium,webkit}=require(process.env.XHANDLE_PLAYWRIGHT_PATH||'playwright-core');
(async()=>{
 const browser=process.env.VERIFY_BROWSER==='webkit'?await webkit.launch({headless:true}):await chromium.launch({headless:true,executablePath:process.env.XHANDLE_CHROME_PATH});
 const results=[];
 try {
  for(const mode of (process.env.REVIEW_MODES?.split(',') || ['saved-manual','saved-nested','saved-auto','auto-arrange','unsaved','immediate-reload','save-during-generation','storage-failure'])){
   const page=await browser.newPage({viewport:{width:1500,height:1000}});
   const id='description-review',key=`diagram:positions:${id}`, generated=`Magic description for ${mode}.`;
   await page.addInitScript(({id,key,mode})=>{
    const set=Storage.prototype.setItem;
    Storage.prototype.setItem=function(k,v){
     if(window.__rejectDescriptionSave && k===key+':groups:v1')throw new DOMException('Diagnostic quota failure','QuotaExceededError');
     return set.call(this,k,v);
    };
    if(sessionStorage.getItem('description-seeded'))return;
    localStorage.setItem('xhandle.projects',JSON.stringify([{id,name:'Description investigation'}]));
    localStorage.setItem('xhandle.sidebarProjectsOpen','true');
    localStorage.setItem('xhandle.projectData',JSON.stringify({[id]:{responseRows:[{subsystem:'Planning',fromFunction:'Plan',controlAction:'Command',toFunction:'Control'}]}}));
    if(!['saved-auto','auto-arrange'].includes(mode)){
     const nested=mode==='saved-nested';
     localStorage.setItem(key+':groups:v1',JSON.stringify([
      ...(nested?[{id:'g:system',label:'Vehicle',elementType:'system',position:{x:0,y:0},width:900,height:700}]:[]),
      {id:'g:planning',label:'Planning',position:{x:100,y:100},width:750,height:400,...(nested?{parentNode:'g:system'}:{})}
     ]));
     localStorage.setItem(key,JSON.stringify([['n:Plan',{position:{x:30,y:60},parentId:'g:planning',groupingIntent:'explicit'}],['n:Control',{position:{x:400,y:60},parentId:'g:planning',groupingIntent:'explicit'}]]));
     localStorage.setItem(key+':initial-layout:v1','complete');
    }
    sessionStorage.setItem('description-seeded','true');
   },{id,key,mode});
   let release;
   const pending=new Promise(resolve=>release=resolve);
   await page.route('**/api/chat',async route=>{
    if(mode==='save-during-generation')await pending;
    await route.fulfill({json:{choices:[{message:{content:generated}}]}});
   });
   const open=async()=>{
    await page.getByRole('button',{name:'Description investigation',exact:true}).click({timeout:60000});
    await page.waitForFunction(()=>document.querySelector('.react-flow')?.style.visibility==='visible');
    await page.waitForTimeout(600);
   };
   const read=()=>page.evaluate(key=>JSON.parse(localStorage.getItem(key+':groups:v1')).filter(box=>box.label==='Planning').map(box=>({id:box.id,description:box.description,edited:box.descriptionUserEdited,auto:box.autoGenerated})),key);
   await page.goto(process.env.XHANDLE_URL||'http://localhost:3000');await open();
   await page.getByTitle('Fit entire diagram to view',{exact:true}).click();await page.waitForTimeout(700);
   const group=page.locator('.project-group-drag-handle').filter({hasText:/^Planning$/}).first();
   await group.dblclick();
   await page.getByRole('button',{name:'Regenerate description with AI',exact:true}).click();
   if(mode!=='save-during-generation')await page.waitForFunction(text=>[...document.querySelectorAll('textarea')].some(el=>el.value===text),generated);
   const draftBeforeSave=await read();
   if(mode==='storage-failure')await page.evaluate(()=>window.__rejectDescriptionSave=true);
   let committedBeforeAction=null;
   if(mode==='immediate-reload'){
    await page.evaluate(()=>{[...document.querySelectorAll('button')].find(b=>b.textContent.trim()==='Save').click();setTimeout(()=>location.reload(),0);});
    await page.waitForEvent('load');await open();
   }else{
    if(mode!=='unsaved')await page.getByRole('button',{name:'Save',exact:true}).click();
    if(mode==='save-during-generation'){release();await page.waitForTimeout(300);}
    await page.waitForTimeout(400);
    committedBeforeAction=await read();
    if(mode==='auto-arrange'){
     await page.getByTitle('Auto arrange',{exact:true}).click();await page.waitForTimeout(800);
    }
    await page.reload();await open();
   }
   const after=await read();
   const result={mode,draftBeforeSave,committedBeforeAction,after,persisted:after.some(box=>box.description===generated)};
   results.push(result);console.log(JSON.stringify(result));
   if(mode.startsWith('saved-'))assert(after.some(box=>box.description===generated),`${mode} unexpectedly lost description`);
   await page.close();
  }
  console.log(JSON.stringify({browser:process.env.VERIFY_BROWSER||'chromium',results},null,2));
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
